public void cargarDatosParaModificar(String dni, String nom, String ape, String tel, String dir, String sex) {

    r1.setText(nom);
    r2.setText(ape);
    r3.setText(dni);
    r4.setText(tel);
    r5.setText(dir);
   
    if (sex != null) {
        if (sex.equalsIgnoreCase("Masculino")) {
            masculino.setSelected(true);
        } else if (sex.equalsIgnoreCase("Femenino")) {
            femenino.setSelected(true);
        }
    }
    try {
        java.sql.Connection con = conexion.Conexion.conectar();
        java.sql.PreparedStatement ps = con.prepareStatement("SELECT id_cliente FROM clientes WHERE dni = ?");
        ps.setString(1, dni);
        java.sql.ResultSet rs = ps.executeQuery();
        if(rs.next()){
            idSeleccionado = rs.getInt("id_cliente"); 
        }
        con.close();
    } catch (Exception e) {
        System.out.println("Error al buscar ID oculto: " + e.getMessage());
    }
}
    
    public void mostrarDatos(){
    String[] titulos = {"ID", "Nombres", "Apellido", "DNI", "Teléfono", "Dirección", "Sexo"};
    DefaultTableModel modelo = new DefaultTableModel(null, titulos);
    String sql = "SELECT id_cliente, nombres, apellidos, dni, telefono, direccion, sexo FROM clientes";
    
    try {
        java.sql.Connection con = conexion.Conexion.conectar();
        java.sql.Statement st = con.createStatement();
        java.sql.ResultSet rs = st.executeQuery(sql);
        
        String[] datos = new String [7]; 
        
        while(rs.next()) {
            datos[0]=rs.getString("id_cliente");
            datos[1]=rs.getString("nombres");
            datos[2]=rs.getString("apellidos");
            datos[3]=rs.getString("dni");
            datos[4]=rs.getString("telefono");
            datos[5]=rs.getString("direccion");
            datos[6]=rs.getString("sexo"); 
            modelo.addRow(datos);
        }
        tablaClientes.setModel(modelo);
        con.close();
    } catch(Exception e) {
        JOptionPane.showMessageDialog(null, "Error al mostrar datos: " + e.getMessage());
    }
}

