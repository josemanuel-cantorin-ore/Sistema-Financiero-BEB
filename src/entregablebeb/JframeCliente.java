    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
    String nombre = r1.getText();
    String apellido = r2.getText();
    String DNI = r3.getText();
    String telefono = r4.getText();
    String direccion = r5.getText();
    String sexo = masculino.isSelected() ? "Masculino" : "Femenino";
  
    if (nombre.isEmpty() || apellido.isEmpty() || DNI.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, complete los campos Obligatorios");
        return;
    } 
    try {
        java.sql.Connection con = conexion.Conexion.conectar();
        String sql = "INSERT INTO clientes (dni, nombres, apellidos, sexo, telefono, direccion, Asesores_Financieros_id_asesor) VALUES (?, ?, ?, ?, ?, ?, ?)";
        java.sql.PreparedStatement ps = con.prepareStatement(sql);
        
        ps.setString(1, DNI);
        ps.setString(2, nombre);
        ps.setString(3, apellido);
        ps.setString(4, sexo); 
        ps.setString(5, telefono);
        ps.setString(6, direccion);
        ps.setInt(7, 1);

        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Cliente registrado correctamente");
        mostrarDatos();
        con.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
   
   
    }//GEN-LAST:event_btnGuardarActionPerformed

