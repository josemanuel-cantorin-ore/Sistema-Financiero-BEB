    private void eliminarClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_eliminarClienteActionPerformed
    int fila = tablaBuscar.getSelectedRow();
    
    if(fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, seleccione un Cliente de la tabla para eliminar.");
    }
    String dniSeleccionado = tablaBuscar.getValueAt(fila, 0).toString();
    
    int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, "¿Estás segur@ que desea eliminar al cliente con DNI: " + dniSeleccionado + "?",
    "Confirmar eliminacion", javax.swing.JOptionPane.YES_NO_OPTION);
    
    if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
        try{
            java.sql.Connection con = conexion.Conexion.conectar();
            
            String sql = "DELETE FROM clientes WHERE dni = ?";
            java.sql.PreparedStatement ps = con.prepareStatement(sql);
            
            ps.setString(1, dniSeleccionado);
            int resultado = ps.executeUpdate();
            
            if(resultado > 0){
                javax.swing.JOptionPane.showMessageDialog(this, "Clientes eliminado correctamente.");
                
                String filtroElegido = ComboBoxBuscar.getSelectedItem().toString();
                String textoBuscado = txtBuscar.getText();
                buscarClientes(filtroElegido, textoBuscado);
                
            }
            con.close();
            
        }catch(java.sql.SQLException ex) {
        if (ex.getErrorCode() == 1451) 
        {javax.swing.JOptionPane.showMessageDialog(this,"OPERACIÓN DENEGADA: \nNo se puede eliminar a este cliente porque tiene Cuentas de Ahorro o transacciones activas.\nDebe eliminar sus cuentas primero.",
                "Cliente con cunetas activas", javax.swing.JOptionPane.WARNING_MESSAGE);
        }else {javax.swing.JOptionPane.showMessageDialog(this, "Error SQL al eliminar" + ex.getMessage());}
    
        }catch(Exception e) {javax.swing.JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_eliminarClienteActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
                                     
    int fila = tablaBuscar.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, seleccione un cliente de la tabla para modificar.");
        return;
    }

    // Capturamos los datos de la fila seleccionada
    String dni = tablaBuscar.getValueAt(fila, 0).toString();
    String nombres = tablaBuscar.getValueAt(fila, 1).toString();
    String apellidos = tablaBuscar.getValueAt(fila, 2).toString();
    String telefono = tablaBuscar.getValueAt(fila, 3).toString();
    String direccion = tablaBuscar.getValueAt(fila, 4).toString();
    // CORRECCIÓN: Capturamos el sexo de la nueva columna (indice 5)
    String sexo = tablaBuscar.getValueAt(fila, 5).toString(); 
    
    JframeCliente ventanaModificar = new JframeCliente();
    
    // CORRECCIÓN: Pasamos el sexto parámetro (sexo)
    ventanaModificar.cargarDatosParaModificar(dni, nombres, apellidos, telefono, direccion, sexo);
    
    ventanaModificar.setVisible(true);
    this.dispose();

    }//GEN-LAST:event_jButton3ActionPerformed

