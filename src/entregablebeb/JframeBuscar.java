    public void buscarClientes(String filtro, String valorBuscar){
    String[] titulos = {"DNI", "Nombres", "Apellidos", "Telefono", "Dirección", "Sexo"};
    javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(null, titulos);
    
    String columna = "dni";
    if (filtro.equals("Apellido")) {
        columna="apellidos";
    } else if (filtro.equals("Nombre")){
        columna="nombres";
    }

    String sql = "SELECT dni, nombres, apellidos, telefono, direccion, sexo FROM clientes WHERE " + columna + " LIKE ?";
    
    try {
        java.sql.Connection con = conexion.Conexion.conectar();
        java.sql.PreparedStatement ps = con.prepareStatement(sql);
        
        ps.setString(1, "%" + valorBuscar + "%");
        java.sql.ResultSet rs = ps.executeQuery();
        String[] datos = new String[6]; 
        
        while(rs.next()) {
            datos[0]=rs.getString("dni");
            datos[1]=rs.getString("nombres");
            datos[2]=rs.getString("apellidos");
            datos[3]=rs.getString("telefono");
            datos[4]=rs.getString("direccion");
            datos[5]=rs.getString("sexo"); 
            modelo.addRow(datos);
        }
        tablaBuscar.setModel(modelo);
        con.close();
        
    } catch(Exception e) {
        JOptionPane.showMessageDialog(null, "Error al buscar: " + e.getMessage());
    }

    

    
}

